-- 0010 引当に「その予約がどの月のものか」を持たせる
--
--   ★なぜ要るのか（2026-10-07・Codex関門②）
--     移行は何度も流し直す。そのたびに「古い引当を消して入れ直す」必要がある。
--     ところが消す対象を正しく絞れなかった。
--
--       month_key … 月額のとき「どの月の枠から引いたか」。チケット・振替は NULL
--       → チケットや振替の引当が、どの月の予約なのか分からない
--       → 「2026-10〜2026-11 の引当だけ消す」ができない
--
--     結果、**予約が削除された／日付変更で対象期間の外へ移った**場合に、
--     その古い引当が残り、used が過大になる。残数が実際より少なく見え、
--     予約できなくなる。
--
--   resv_month は「予約が属する月」。source に関係なく必ず入る。
--   month_key（どの枠から引いたか）とは意味が違うので、別の列にする。
--
--   既存の行は0件（引当はまだ入れていない）ので、既定値で埋まっても実害は無い。
--   アプリ側は必ず値を入れる。

ALTER TABLE reservation_allocations ADD COLUMN resv_month TEXT NOT NULL DEFAULT '';

-- 「この会員の、この期間の引当」を引くための索引。消すときに使う。
CREATE INDEX IF NOT EXISTS idx_alloc_cust_month
  ON reservation_allocations(customer_id, resv_month);
