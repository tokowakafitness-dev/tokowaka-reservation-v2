-- 0012 枠の行に「契約がこの月をどう覆っているか」を持たせる（3状態）
--
--   ★なぜ要るのか（2026-10-07・全パターン検証 A5 で発覚）
--     計算側（Allocate.js の _lbComputeRemaining）は、同じ月について**2つの違う答え**を出す。
--
--       会員に見せる残数   契約が対象月を覆わなければ 0（繰越が残っていても）
--       内部の消化         その月の予約は monthly に割り当て、繰越から引く
--
--     業務上の意味は「契約が切れたら新しくは取れないが、入っている予約は繰越で処理する」。
--     D1でこれを1つの数字にすると、どちらかが必ず壊れる：
--       quota = 繰越ぶん → 見せる残数が1以上になり、計算側の0と食い違う
--       quota = 0        → 予約が1件入ると −1。計算側は0なので、やはり食い違う
--       行を作らない     → 引当の親が無く外部キー違反（本番で error code 1101 が実際に出た）
--
--   ★なぜ 1/0 ではなく3状態なのか（Codex指摘・2026-10-07）
--     計算側は3つを区別している。1bitでは表せない。
--
--       uncovered  契約が対象月を覆っていない        → 見せる残数 0
--       limited    覆っていて頻度がある              → 見せる残数 quota − used
--       unlimited  覆っているが頻度が未設定          → 見せる残数 null（上限なし）
--
--     頻度欄が空の月額契約は freq=0 になり、問題としても扱われない（Allocate.js の
--     `var freq = cc.freq >= 0 ? Number(r[cc.freq] || 0) : 0;`）。
--     前月に繰越が出ていれば、その月も avail > 0 で枠の行ができる。
--     1bit（covered=0）にすると、この「上限なし」の月を「残数0」として書いてしまう。
--
--   ★なぜ既定値を入れないのか（Codex指摘・2026-10-07）
--     この列を足す前のコードは `avail`（頻度＋繰越）で行を作っていた。
--     つまり既にある行には **uncovered の月も unlimited の月も混ざっている可能性がある**。
--     既定を 'limited' にすると、本当は0やnullを見せるべき行が数値を見せる。
--     どの会員かはD1だけでは分からない。
--
--     だから既定値を入れず NULL のままにする。NULL ＝「まだ作り直していない行」。
--     照合（quota-verify）は NULL を**一致ではなく未解決として数え、不合格にする**。
--     移行の手順は：この列を足す → 全期間を作り直す → 照合で NULL が0件になるのを確認。
--
--   quota はそのまま「割当器が引ける回数（頻度＋繰越）」。消化の記録はこれで回る。

ALTER TABLE monthly_quota ADD COLUMN coverage TEXT
  CHECK (coverage IS NULL OR coverage IN ('uncovered', 'limited', 'unlimited'));
