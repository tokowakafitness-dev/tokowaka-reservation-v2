-- 0011 チケットに「移行前に既に使っていた枚数」を持たせる
--
--   ★なぜ要るのか（2026-10-07・オーナー指摘）
--     店舗のオープンは3月、契約の最も古い開始も3月。
--     しかしLINE予約の台帳は**9月から**しか記録が無い。
--     3月〜8月の消化は、棚卸し（migration_balance）で引き継いでいる。
--
--     計算側は、その引継ぎを「使った数の初期値」として持っている
--     （allocate.js の openingPacks[packId] = 締め済み消化枚数）。
--     ところがD1側は**引当だけが used を増やす**ので、3月〜8月ぶんが入らない。
--
--       計算側の使った数 ＝ 棚卸しの引継ぎ（3〜8月） ＋ 引当（9月〜）
--       D1側の使った数   ＝ 引当（9月〜）だけ        ← 足りない
--
--     そのため照合で、D1のチケット残が計算より多く出た（20名）。
--     放置して読み取りをD1へ向けると、**使えないはずのチケットが使えてしまう。**
--
--   ★なぜ used に直接足さないのか
--     「used を動かすのはトリガーだけ」が設計の不変条件。
--     棚卸しぶんを used に混ぜると、引当を作り直すたびに消えるか二重になる。
--     別の列にして、残り ＝ total − opening_used − used とする。
--
--   月額の繰越は quota にすでに含まれている（avail = 頻度 ＋ 繰越、繰越は棚卸し由来）。
--   実際の照合でも月額は20名全員で一致していた。だからここではチケットだけを直す。

ALTER TABLE ticket_packs ADD COLUMN opening_used INTEGER NOT NULL DEFAULT 0;
