-- 0019 作業依頼の結果を読むのに「読み取りの鍵」を必須にする（2026-10-16・セキュリティ）
--
--   ★解く問題
--     結果の読み取りは「request_id を知っていること」だけが鍵だった（合言葉なし）。
--     ところが request_id を書く ops/job.json は**一般公開のリポジトリ**にある＝誰でも番号が分かる。
--     結果には「個人情報を入れない」前提だったが、日次点検の結果に**顧客の氏名**が入る回があった
--     （例：担当calの残骸「10/22 20:00 〇〇様」）。＝氏名が外から読める状態だった。
--
--   ★直し方
--     依頼のたびに CEO が手元で鍵を作り、公開するのは鍵の SHA-256（args._rk）だけ。
--     読むときは ?k=<鍵> を付け、Worker が SHA-256 を比べる。鍵はどこにも公開されない。
--     鍵の無い（古い）依頼の結果は返さない。
--   ★すでに残っている依頼は**行ごと消す**（関門②・Codex）。結果だけ消すと、この migration の後〜新しい Worker が
--     公開されるまでの間に、実行中の GAS が報告して古い Worker が結果を書き戻し、IDだけで読める時間ができる。
--     行が無ければ報告の UPDATE（status='running' の行だけ）は0行になり、結果は戻らない。
--     鍵の無い古い依頼は読めなくする方針なので、残す利益は無い。
--   ★適用中は ops/job.json を push しない。

ALTER TABLE jobs ADD COLUMN read_key_hash TEXT;

